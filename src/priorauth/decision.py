"""The decision is computed in cdeo from per-criterion results,
never generated by the model. 

The model's job is narrower and checkable: judge each criterion and quote the evidence.
Keeping the final call in plain code makes it auditable, and text injected into a chart 
cannot change it.
"""

from priorauth.schemas import CriterionResult, CriterionStatus, Decision, Policy


def decide(policy: Policy, results: list[CriterionResult]) -> Decision:
    """Turn criterion results into a decision. Never raises: anything unexpected escalates."""
    required = [c.criterion_id for c in policy.criteria if c.required]
    if not required: # nothing was verified, so "ready" would mean nothing
        return Decision.ESCALATE

    ids = [r.criterion_id for r in results]
    if len(ids) != len(set(ids)): # a criterion was judged twice, possibly with conflicting answers
        return Decision.ESCALATE

    if not set(ids) <= {c.criterion_id for c in policy.criteria}:  # a result names a criterion this policy lacks
        return Decision.ESCALATE

    status = {r.criterion_id: r.status for r in results}
    if any(cid not in status for cid in required): # a required criterion was skipped
        return Decision.ESCALATE

    required_statuses = [status[cid] for cid in required]
    if CriterionStatus.NOT_MET in required_statuses:
        return Decision.ESCALATE
    if CriterionStatus.INSUFFICIENT_EVIDENCE in required_statuses:
        return Decision.NEEDS_DOCUMENTATION
    return Decision.READY_TO_SUBMIT

        